#!/usr/bin/env python3
"""Which codepoints each bundled cover face can draw (D-148 for the cover packs, D-164).

Reads the TTFs the cover packs register in app/_layout.tsx and writes lib/coverFontCoverage.ts:
one packed codepoint list per face, in the same base-36 delta encoding lib/displayFont.ts reads
for the display face. A title is set in a pack's face only when every glyph of it is in that
face's list; otherwise the whole title keeps the system stack. Never a mixture.

Usage (from novaku-app/):
    python scripts/build-cover-font-coverage.py
"""
from pathlib import Path

from fontTools.ttLib import TTFont

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
FONTS = ROOT / "node_modules" / "@expo-google-fonts"
OUT = ROOT / "lib" / "coverFontCoverage.ts"

# family name registered with expo-font -> package file
FACES = {
    "Caveat_700Bold": "caveat/700Bold/Caveat_700Bold.ttf",
    "PatrickHand_400Regular": "patrick-hand/400Regular/PatrickHand_400Regular.ttf",
    "Kalam_700Bold": "kalam/700Bold/Kalam_700Bold.ttf",
    "PermanentMarker_400Regular": "permanent-marker/400Regular/PermanentMarker_400Regular.ttf",
    "RockSalt_400Regular": "rock-salt/400Regular/RockSalt_400Regular.ttf",
    "CoveredByYourGrace_400Regular": "covered-by-your-grace/400Regular/CoveredByYourGrace_400Regular.ttf",
    "AmaticSC_700Bold": "amatic-sc/700Bold/AmaticSC_700Bold.ttf",
    "PlayfairDisplay_800ExtraBold": "playfair-display/800ExtraBold/PlayfairDisplay_800ExtraBold.ttf",
    "Lobster_400Regular": "lobster/400Regular/Lobster_400Regular.ttf",
}

# The Chinese faces (D-166) are our own subsets, built by build-cover-cjk-fonts.py and loaded on
# demand from assets/fonts/cover rather than registered at start-up.
CJK_DIR = ROOT / "assets" / "fonts" / "cover"
CJK_FACES = [
    "ZCOOLKuaiLe_Cover",
    "MaShanZheng_Cover",
    "LongCang_Cover",
    "ZhiMangXing_Cover",
    "NotoSerifSC900_Cover",
    "SmileySans_Cover",
]


# Advance widths are read for Latin (Basic Latin through Latin Extended-B): the cover counts the
# lines a title wraps into from them, because one width model for fifteen faces was off by a
# quarter either way (D-166). Han, kana and Hangul are a full em in every face here.
ADVANCE_RANGE = range(0x20, 0x250)


def packed_advances(font: TTFont) -> str:
    """'delta:advance' pairs, base 36, advance in thousandths of an em."""
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    upm = font["head"].unitsPerEm
    out = []
    previous = 0
    for cp in ADVANCE_RANGE:
        if cp not in cmap:
            continue
        advance = round(hmtx[cmap[cp]][0] * 1000 / upm)
        out.append(f"{base36(cp - previous)}:{base36(advance)}")
        previous = cp
    return ".".join(out)


def packed(codepoints: list[int]) -> str:
    out = []
    previous = 0
    for cp in sorted(codepoints):
        out.append(base36(cp - previous))
        previous = cp
    return ".".join(out)


def base36(n: int) -> str:
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    if n == 0:
        return "0"
    s = ""
    while n:
        n, r = divmod(n, 36)
        s = digits[r] + s
    return s


def main() -> int:
    lines = [
        "// Generated by scripts/build-cover-font-coverage.py. Do not edit.",
        "// Packed as base-36 deltas between sorted codepoints; lib/coverFonts.ts unpacks it.",
        "",
        "export const COVER_FONT_PACKED_COVERAGE: Record<string, string> = {",
    ]
    sources = [(family, FONTS / rel) for family, rel in FACES.items()]
    sources += [(family, CJK_DIR / f"{family}.ttf") for family in CJK_FACES]
    advances = []
    # The display face sets the titles of covers without a pack (lib/displayFont.ts); its
    # coverage lives in displayFontCoverage.ts, so only its advances are written here.
    display = TTFont(ROOT / "assets" / "fonts" / "PosterviaDisplay-Bold.otf", lazy=True)
    advances.append(f"  'PosterviaDisplay-Bold': '{packed_advances(display)}',")
    for family, path in sources:
        font = TTFont(path, lazy=True)
        cmap = font.getBestCmap()
        cps = [cp for cp in cmap if cp >= 0x20]
        lines.append(f"  {family}: '{packed(cps)}',")
        advances.append(f"  {family}: '{packed_advances(font)}',")
        print(f"{family}: {len(cps)} codepoints")
    lines.append("};")
    lines.append("")
    lines.append("// Latin advance widths: base-36 'codepoint delta:thousandths of an em' pairs.")
    lines.append("export const COVER_FONT_PACKED_ADVANCES: Record<string, string> = {")
    lines.extend(advances)
    lines.append("};")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"-> {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
